require('dotenv').config()
const express = require('express')
const cors = require('cors')
const helmet = require('helmet')
const cookieParser = require('cookie-parser')
const connectDB = require('./config/db')
const { csrfGuard } = require('./middleware/authMiddleware')
const { notFound, errorHandler } = require('./middleware/errorHandler')
for (const k of ['JWT_SECRET', 'MONGODB_URI', 'CLIENT_URL']) if (!process.env[k]) { console.error(`Missing ${k}. Copy server/.env.example to server/.env`); process.exit(1) }
if (process.env.JWT_SECRET.length < 32) { console.error('JWT_SECRET must be at least 32 characters'); process.exit(1) }
const app = express()
app.disable('x-powered-by')
app.use(helmet())
app.use(cors({ origin: process.env.CLIENT_URL, credentials: true }))
app.use(express.json({ limit: '50kb' }))
app.use(cookieParser())
app.get('/api/health', (req, res) => res.json({ status: 'ok', time: new Date().toISOString() }))
app.use('/api', csrfGuard)
app.use('/api/auth', require('./routes/authRoutes'))
app.use('/api/reports', require('./routes/reportRoutes'))
app.use(notFound)
app.use(errorHandler)
connectDB().then(() => app.listen(process.env.PORT || 5000, () => console.log(`API on :${process.env.PORT || 5000}`)))
  .catch(e => { console.error('Could not connect to MongoDB:', e.message); process.exit(1) })
